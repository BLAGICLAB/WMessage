/** 主导航栏宽度（px）——**单一真相源**，不是随手写的视觉参数。
 *
 * 为什么要从 CSS 类里搬出来：任务编辑浮窗滑出屏幕时要越过左缘，那个偏移是
 * JS 里算的常量，跟着 Tailwind 的 `w-52` 改就会静默错位（浮窗收进导航栏底下，
 * 看不出来只觉「动画怪」）。宽度必须能被 import，两处才能真的同步。
 *
 * 取值走「最宽一行装得下」而不是「典型一行够用」：最宽的是行动钮
 * 「新建任务 + ⌘N」（`NAV_ROW_MIN_W` 算式），不是导航项里的「回收站」。
 * 按典型行取 160px 时短了一两个像素，标签就被截成「新建…」——差这点余量
 * 换个字体或系统字号就翻车，所以留够一个汉字（14px）。
 *
 * 主导航与设置页左栏是同一个壳，共用这一个宽度：设置页行更窄（没有快捷键
 * 提示条），拿主导航的宽度给它只会有余，不会截断。
 */
export const NAV_W = 184;

/** 主导航与浮窗左缘的间距 */
export const NAV_GAP = 4;

/** 导航里最长的标签：行动钮「新建任务」四个字。改文案时这里一并改。 */
export const NAV_LONGEST_LABEL = "新建任务";

/** 一行导航的最小装法（px，偏保守）：
 *  nav p-3(24) + border-r(1) + 按钮 border(2) + 行内边距 px-2.5(20)
 *  + 图标(15) + gap×2(16) + 标签（汉字按 1em=14px 计）
 *  + 快捷键提示条(34，按 Windows 的「Ctrl+N」算，它比 mac 的「⌘N」宽) */
export const NAV_ROW_MIN_W =
  24 + 1 + 2 + 20 + 15 + 16 + NAV_LONGEST_LABEL.length * 14 + 34;
