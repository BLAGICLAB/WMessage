/** 主导航栏宽度（px）——**单一真相源**，不是随手写的视觉参数。
 *
 * 为什么要从 CSS 类里搬出来：任务编辑浮窗滑出屏幕时要越过左缘，那个偏移是
 * JS 里算的常量，跟着 Tailwind 的 `w-52` 改就会静默错位（浮窗收进导航栏底下，
 * 看不出来只觉「动画怪」）。宽度必须能被 import，两处才能真的同步。
 *
 * 取值依据（text-sm = 14px，导航项最长是「回收站」三个汉字）：
 * - 导航项：行内边距 20 + 图标 15 + 间距 8 + 标题 42 ≈ 85px
 * - 行动钮（新建/搜索）：上面三项 + ⌘K 提示条 ≈ 120px（Windows 下 Ctrl+K 更宽）
 * - 分区标题「Agent 能力」：20 + 中英混排 ≈ 88px
 * 取 160px：覆盖最宽一档还留约 40px 余量。再窄就会逼出省略号，
 * 再宽则是白占聊天区的宽度——省下的 48px 原样转给会话栏（见 SessionRail）。
 */
export const NAV_W = 160;

/** 主导航与浮窗左缘的间距 */
export const NAV_GAP = 4;
