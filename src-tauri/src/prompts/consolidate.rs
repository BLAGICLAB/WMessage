//! 长期记忆整理提示词（memory::consolidate 定时整理用）：输出 JSON
//! `{"ops":[…], "lesson":"可选的行为准则"}`，解析失败即跳过本轮，
//! 措辞是唯一的格式防线。lesson 是自进化提案的内容源（行为准则，
//! 与 ops 沉淀的事实类 reflection 刻意拉开语义距离，防候选池撞车）。

/// 整理 prompt（中文；给 LLM 的条目标注真实 id，指令回指同一 id）
pub(crate) const CONSOLIDATE_PROMPT: &str = "\
你是记忆整理助手。下面是助手的长期记忆条目（格式：id | 类型 | 重要度1-5 | 内容）。\
请做一轮整理反思，只输出一个 JSON（不要输出其它任何文字），格式：\
{\"ops\":[\
{\"action\":\"merge\",\"ids\":[\"id1\",\"id2\"],\"content\":\"合并后的内容\"},\
{\"action\":\"contradiction\",\"keep\":\"保留的id\",\"drop\":\"删除的id\",\"content\":\"裁决后保留条目的新内容\"},\
{\"action\":\"distill\",\"ids\":[\"id1\",\"id2\"],\"content\":\"从这些条目提炼出的规律或反思\"}],\"lesson\":\"可选：一条机器人以后可执行的行为准则\"}。\
规则：merge 用于内容重复或互补的条目；contradiction 用于互相矛盾的条目（按重要度和新旧裁决,\
保留更可靠的那条并把它的内容更新准确；drop 是不可逆删除，两段内容矛盾不明显或拿不准时\
宁可不裁决、输出 {\"ops\":[]} 留给下一轮）；distill 用于从多条相关记忆提炼一般规律。\
没有值得做的就输出 {\"ops\":[]}。所有 content 用中文、各不超过 500 字。ids 必须原样引用上面的 id，\
且每个 id 在整张 ops 数组中至多出现一次（不允许既 keep 又 drop，也不允许两个 op 同时引用它）。\
lesson 规则：仅当本轮整理揭示了一条机器人**以后该怎么做**的行为准则时才填写——\
写成「遇到 X 应该 Y」式的可执行做法或判断标准；**禁止复述条目里的事实内容**（那已由 ops 沉淀，\
重复写入会被拒）；与既有记忆重复、或拿不准时省略该字段；40-200 字中文。";
